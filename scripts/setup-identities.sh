#!/usr/bin/env bash
# Create or reuse the standard ProcureSettle identities and fund them with friendbot.
set -euo pipefail

usage() {
  printf '%s\n' \
    'Usage: scripts/setup-identities.sh [options]' \
    '' \
    'Creates or reuses the buyer, supplier, and issuer identities, requests' \
    'friendbot funding for each, prints their public keys, and writes an' \
    'identity mapping to a local config file. Secret keys are never printed.' \
    '' \
    'Options:' \
    '  --network <name>     Network to fund on (default: local)' \
    '  --config-dir <path>  Stellar CLI config directory' \
    '                       (default: $STELLAR_CONFIG_DIR or $HOME/.config/stellar)' \
    '  --output <path>      Identity mapping file' \
    '                       (default: <config-dir>/identities.env)' \
    '  -h, --help           Show this help'
}

die() {
  printf 'error: %s\n' "$1" >&2
  exit 1
}

network="${NETWORK:-local}"
config_dir="${STELLAR_CONFIG_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/stellar}"
output_file="${IDENTITIES_FILE:-}"
identities=(buyer supplier issuer)
declare -A public_keys

while [[ $# -gt 0 ]]; do
  case "$1" in
    --network)
      [[ $# -ge 2 ]] || die "--network requires a value"
      network="$2"
      shift 2
      ;;
    --config-dir)
      [[ $# -ge 2 ]] || die "--config-dir requires a value"
      config_dir="$2"
      shift 2
      ;;
    --output)
      [[ $# -ge 2 ]] || die "--output requires a value"
      output_file="$2"
      shift 2
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      die "unknown option: $1"
      ;;
  esac
done

command -v stellar >/dev/null 2>&1 || die "stellar CLI is not installed"

if [[ -z "$output_file" ]]; then
  output_file="$config_dir/identities.env"
fi

mkdir -p "$config_dir"
stellar_cli=(stellar --config-dir "$config_dir")

for identity in "${identities[@]}"; do
  if public_key=$("${stellar_cli[@]}" keys public-key "$identity" 2>/dev/null); then
    printf 'Reusing existing %s identity: %s\n' "$identity" "$public_key"
  else
    "${stellar_cli[@]}" keys generate "$identity" >/dev/null
    public_key=$("${stellar_cli[@]}" keys public-key "$identity")
    printf 'Generated %s identity: %s\n' "$identity" "$public_key"
  fi
  public_keys["$identity"]="$public_key"
done

for identity in "${identities[@]}"; do
  printf 'Requesting friendbot funding for %s on %s: %s\n' \
    "$identity" "$network" "${public_keys[$identity]}"
  if ! "${stellar_cli[@]}" keys fund "$identity" --network "$network" >/dev/null; then
    printf 'Friendbot rejected %s; it may already be funded.\n' "$identity" >&2
  fi
done

mkdir -p "$(dirname "$output_file")"
tmp_file="$(mktemp "${output_file}.XXXXXX")"
trap 'rm -f "$tmp_file"' EXIT
{
  printf '# Generated by scripts/setup-identities.sh\n'
  printf 'NETWORK=%s\n' "$network"
  printf 'BUYER_ADDRESS=%s\n' "${public_keys[buyer]}"
  printf 'SUPPLIER_ADDRESS=%s\n' "${public_keys[supplier]}"
  printf 'ISSUER_ADDRESS=%s\n' "${public_keys[issuer]}"
} >"$tmp_file"
chmod 600 "$tmp_file"
mv "$tmp_file" "$output_file"
trap - EXIT

printf 'Identity mappings written to %s\n' "$output_file"
